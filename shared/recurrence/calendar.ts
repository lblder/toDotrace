/**
 * 月 / 年算术接缝 —— `shared/recurrence` 里**唯一**碰月 / 年日期运算的地方。
 *
 * ADR-011 §3 把两件事拆开：
 * - **策略**（要不要夹取、夹到哪）= 本模块的 §3：`落库日 = min(规则日, 该月天数)`，`-1` 永不夹取；
 * - **算术**（加 N 个月、这个月有几天）= `shared/time` 的 ADR-009 §8。
 *
 * 02 §5 与 03 §2 都规定「时间折算全局唯一一份，任何模块不得私写日期折算」。
 * 本文件是这条纪律的**物理接缝**：其它文件一律经这三个函数，谁都不许自己写
 * `month ± 1`、闰年判定或 `daysInMonth`。要换实现（或加缓存）只动这里。
 *
 * 选 `*Clamped` 而非抛错版，是 ADR-009 §8 的明文指定（「这是重复模块应当使用的那个」）：
 * 抛错版留给「调用方自己先判定合法性」的场景，而 §3 已经裁决本模块**夹取**。
 *
 * ⚠️ **夹取不可逆**：`addMonthsClamped(addMonthsClamped('2026-01-31', 1), -1)` 得到
 * `2026-01-28`，**不是** `2026-01-31`。因此本模块的任何推进都**只从相位原点
 * （`starts_on`）加 k 个间隔**，绝不「先加后减」、绝不以上一轮落库日为基数——
 * 这正是 ADR-011 §5「名义日自始至终取自 `byMonthDay` / `starts_on`，不取自上一轮落库日」
 * 的又一层理由（除了防漂移，还因为夹取本身不可逆）。
 */
